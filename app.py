"""
UiPath Robot Capacity & Gap Analysis — interactive Streamlit dashboard.

Reads output/Free_Slots_Analysis.csv (generated by free_slots_v2.py) and
visualises the KPIs: Total Gaps, Available vs Reserved capacity, per-robot
breakdown, hourly heatmap and duration distribution.

Deploy:  streamlit run app.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
DATA_CSV = BASE_DIR / "data" / "Free_Slots_Analysis.csv"
CHARTS = {
    "capacity": BASE_DIR / "output" / "robot_capacity_breakdown.png",
    "heatmap": BASE_DIR / "output" / "gap_frequency_heatmap.png",
    "distribution": BASE_DIR / "output" / "gap_duration_distribution.png",
}

st.set_page_config(page_title="UiPath Gap Analysis", layout="wide")


@st.cache_data
def load_data(path: str) -> pd.DataFrame:
    """Load the gaps CSV once and cache it."""
    return pd.read_csv(path)


def main() -> None:
    """Render the dashboard."""
    st.title("UiPath Robot Capacity & Gap Analysis")
    st.caption(
        "Idle-window analysis between consecutive UiPath jobs · "
        "source: `data/Free_Slots_Analysis.csv` · see README for methodology"
    )

    if not DATA_CSV.exists():
        st.error(
            f"Data file missing: `{DATA_CSV}` — run `python free_slots_v2.py` first."
        )
        return

    df = load_data(str(DATA_CSV))

    # --- Filters (sidebar) --------------------------------------------------
    with st.sidebar:
        st.header("Filters")
        robots = st.multiselect("Robot", sorted(df["robotName"].unique()))
        gap_types = st.multiselect(
            "Gap type", sorted(df["Gap_Type"].unique()),
            default=sorted(df["Gap_Type"].unique()),
        )
        weekdays = st.multiselect("Weekday", sorted(df["WeekDay"].unique()))

    filt = df
    if robots:
        filt = filt[filt["robotName"].isin(robots)]
    if gap_types:
        filt = filt[filt["Gap_Type"].isin(gap_types)]
    if weekdays:
        filt = filt[filt["WeekDay"].isin(weekdays)]

    # --- KPI cards ----------------------------------------------------------
    total = len(filt)
    available = int((filt["Gap_Type"] == "Available").sum())
    reserved = int((filt["Gap_Type"] == "Reserved_Same_Process").sum())
    post_error = int((filt["Gap_Type"] == "Post_Error_Window").sum())

    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Total gaps", total)
    k2.metric("Available (safe)", available, f"{total and available / total * 100:.1f}%")
    k3.metric("Reserved", reserved, f"{total and reserved / total * 100:.1f}%")
    k4.metric("Post-error", post_error)

    # --- Charts (matplotlib PNGs from free_slots_v2.py) ---------------------
    st.subheader("Capacity breakdown")
    if CHARTS["capacity"].exists():
        st.image(str(CHARTS["capacity"]), use_container_width=True)
    else:
        st.warning("Chart PNG missing — re-run free_slots_v2.py.")

    st.subheader("Gap frequency heatmap")
    if CHARTS["heatmap"].exists():
        st.image(str(CHARTS["heatmap"]), use_container_width=True)

    st.subheader("Duration distribution")
    if CHARTS["distribution"].exists():
        st.image(str(CHARTS["distribution"]), use_container_width=True)

    # --- Data table (Power-BI-style drill-down) -----------------------------
    st.subheader("Gap detail")
    st.dataframe(filt, use_container_width=True)
    st.download_button(
        "Download filtered CSV",
        filt.to_csv(index=False).encode(),
        "filtered_free_slots.csv",
        "text/csv",
    )


if __name__ == "__main__":
    main()
