"""
UiPath Robot Capacity & Gap Analysis — interactive Streamlit dashboard.

Reads data/Free_Slots_Analysis.csv (generated by free_slots_v2.py) and
visualises the KPIs with fully interactive Plotly charts:
  - Total Gaps, Available vs Reserved capacity (KPI cards)
  - Stacked capacity per robot (hover/zoom)
  - Gap-frequency heatmap by hour x robot
  - Gap-duration distribution with min/max threshold markers

All charts are generated live from the CSV — no static PNGs needed at runtime.
Deploy:  streamlit run app.py
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
DATA_CSV = BASE_DIR / "data" / "Free_Slots_Analysis.csv"

# Thresholds (mirror defaults in free_slots_v2.py / Config.xlsx) — shown as
# reference lines on the duration histogram.
MIN_GAP_MINUTES = 30
MAX_GAP_HOURS = 12

GAP_COLORS = {
    "Available": "#2ecc71",
    "Reserved_Same_Process": "#f39c12",
    "Post_Error_Window": "#e74c3c",
}

st.set_page_config(page_title="UiPath Gap Analysis", layout="wide")


def parse_duration_minutes(s: str) -> float:
    """Parse 'X hrs Y mins' / 'Y min Z sec' / 'Z secs' into minutes (float)."""
    if not isinstance(s, str):
        return 0.0
    m = re.match(
        r"(?:(?P<h>\d+)\s*hrs?\s*)?(?:(?P<m1>\d+)\s*mins?\s*)?(?:(?P<s1>\d+)\s*secs?)?",
        s.strip(),
    )
    if not m:
        return 0.0
    return int(m["h"] or 0) * 60 + int(m["m1"] or 0) + int(m["s1"] or 0) / 60.0


def parse_hour(s: str) -> int:
    """Parse 'HH:MM:SS' into hour-of-day (0-23)."""
    try:
        return int(pd.to_datetime(s, format="%H:%M:%S").hour)
    except Exception:
        return 0


@st.cache_data
def load_data(path: str) -> pd.DataFrame:
    """Load the gaps CSV once and derive numeric columns for charting."""
    df = pd.read_csv(path)
    df["Gap_Minutes"] = df["Gap Duration"].map(parse_duration_minutes)
    df["Gap_Hours"] = df["Gap_Minutes"] / 60.0
    df["Gap_Hour"] = df["Gap_From"].map(parse_hour)
    return df


def capacity_chart(filt: pd.DataFrame) -> go.Figure:
    """Stacked horizontal bar: total free hours per robot by Gap_Type."""
    if filt.empty:
        return go.Figure()
    summary = (
        filt.groupby(["robotName", "Gap_Type"])["Gap_Hours"]
        .sum()
        .reset_index()
        .sort_values("Gap_Hours")
    )
    fig = px.bar(
        summary,
        x="Gap_Hours",
        y="robotName",
        color="Gap_Type",
        color_discrete_map=GAP_COLORS,
        barmode="stack",
        orientation="h",
        labels={"Gap_Hours": "Total Free Hours", "robotName": "Robot"},
        title="Robot Capacity Breakdown",
        hover_data={"Gap_Hours": ":.1f"},
    )
    fig.update_layout(xaxis_title="Total Free Hours", yaxis_title="Robot")
    return fig


def heatmap_chart(filt: pd.DataFrame) -> go.Figure:
    """Density heatmap: gap frequency by hour (Gap_From) x robot."""
    if filt.empty:
        return go.Figure()
    counts = pd.crosstab(filt["robotName"], filt["Gap_Hour"])
    counts = counts.reindex(
        columns=range(24), fill_value=0
    )  # all 24 hours, gaps = 0
    long = counts.stack().rename("Gaps").reset_index()
    fig = px.density_heatmap(
        long,
        x="Gap_Hour",
        y="robotName",
        z="Gaps",
        color_continuous_scale="YlOrRd",
        labels={"Gap_Hour": "Hour of Day (0-23)", "robotName": "Robot", "Gaps": "Number of Gaps"},
        title="Gap Frequency by Hour & Robot",
    )
    fig.update_layout(xaxis_title="Hour of Day (0-23)", yaxis_title="Robot")
    return fig


def duration_chart(filt: pd.DataFrame) -> go.Figure:
    """Histogram of gap durations with min/max threshold lines."""
    if filt.empty:
        return go.Figure()
    fig = px.histogram(
        filt,
        x="Gap_Minutes",
        nbins=30,
        color_discrete_sequence=["#3498db"],
        labels={"Gap_Minutes": "Gap Duration (minutes)"},
        title="Distribution of Free Slot Durations",
    )
    fig.update_traces(marker_line_width=1, marker_line_color="black")
    fig.add_vline(
        x=MIN_GAP_MINUTES, line_dash="dash", line_color="#e74c3c",
        annotation_text=f"Min {MIN_GAP_MINUTES} min",
    )
    fig.add_vline(
        x=MAX_GAP_HOURS * 60, line_dash="dash", line_color="#9b59b6",
        annotation_text=f"Max {MAX_GAP_HOURS} hrs",
    )
    return fig


def main() -> None:
    """Render the dashboard."""
    st.title("UiPath Robot Capacity & Gap Analysis")
    st.caption(
        "Idle-window analysis between consecutive UiPath jobs · "
        "source: `data/Free_Slots_Analysis.csv` · see README for methodology"
    )

    if not DATA_CSV.exists():
        st.error(
            f"Data file missing: `{DATA_CSV}` — run `python free_slots_v2.py` first."
        )
        return

    df = load_data(str(DATA_CSV))

    # --- Filters (sidebar) --------------------------------------------------
    with st.sidebar:
        st.header("Filters")
        robots = st.multiselect("Robot", sorted(df["robotName"].unique()))
        gap_types = st.multiselect(
            "Gap type", sorted(df["Gap_Type"].unique()),
            default=sorted(df["Gap_Type"].unique()),
        )
        weekdays = st.multiselect("Weekday", sorted(df["WeekDay"].unique()))

    filt = df
    if robots:
        filt = filt[filt["robotName"].isin(robots)]
    if gap_types:
        filt = filt[filt["Gap_Type"].isin(gap_types)]
    if weekdays:
        filt = filt[filt["WeekDay"].isin(weekdays)]

    # --- KPI cards ----------------------------------------------------------
    total = len(filt)
    available = int((filt["Gap_Type"] == "Available").sum())
    reserved = int((filt["Gap_Type"] == "Reserved_Same_Process").sum())
    post_error = int((filt["Gap_Type"] == "Post_Error_Window").sum())

    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Total gaps", total)
    k2.metric("Available (safe)", available, f"{total and available / total * 100:.1f}%")
    k3.metric("Reserved", reserved, f"{total and reserved / total * 100:.1f}%")
    k4.metric("Post-error", post_error)

    # --- Interactive Plotly charts (all three update with filters) ----------
    st.subheader("Capacity breakdown — Available vs Reserved")
    st.plotly_chart(capacity_chart(filt), use_container_width=True)

    st.subheader("Gap frequency heatmap")
    st.plotly_chart(heatmap_chart(filt), use_container_width=True)

    st.subheader("Duration distribution")
    st.plotly_chart(duration_chart(filt), use_container_width=True)

    # --- Data table (Power-BI-style drill-down) -----------------------------
    st.subheader("Gap detail")
    st.dataframe(filt.drop(columns=["Gap_Minutes", "Gap_Hours", "Gap_Hour"]), use_container_width=True)
    st.download_button(
        "Download filtered CSV",
        filt.to_csv(index=False).encode(),
        "filtered_free_slots.csv",
        "text/csv",
    )


if __name__ == "__main__":
    main()
