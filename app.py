"""
UiPath Robot Capacity & Gap Analysis interactive Streamlit dashboard.

Reads data/Free_Slots_Analysis.csv (generated by free_slots_v2.py) and
visualises the KPIs with fully interactive Plotly charts:
  - Total Gaps, Available vs Reserved capacity (KPI cards)
  - Stacked capacity per robot (hover/zoom)
  - Gap-frequency heatmap by hour x robot
  - Gap-duration distribution with min/max threshold markers

All charts are generated live from the CSV no static PNGs needed at runtime.
Deploy:  streamlit run app.py
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
DATA_CSV = BASE_DIR / "data" / "Free_Slots_Analysis.csv"

# Thresholds (mirror defaults in free_slots_v2.py / Config.xlsx) shown as
# reference lines on the duration histogram.
MIN_GAP_MINUTES = 30
MAX_GAP_HOURS = 12

GAP_COLORS = {
    "Available": "#2ecc71",
    "Reserved_Same_Process": "#f39c12",
    "Post_Error_Window": "#e74c3c",
}

# Human-friendly labels for the filter UI (internal Gap_Type values unchanged).
GAP_LABELS = {
    "Available": "Available safe for new work",
    "Reserved_Same_Process": "Reserved queued for same process",
    "Post_Error_Window": "Post-error after failure/retry window",
}
LABEL_TO_GAP = {v: k for k, v in GAP_LABELS.items()}

WEEKDAY_ORDER = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]

# Discrete stops for the minimum-duration slider (in minutes).
MIN_DURATION_OPTIONS = [0, 30, 60, 120, 180, 240, 360, 480, 600, 720]

st.set_page_config(page_title="UiPath Gap Analysis", layout="wide")


def parse_duration_minutes(s: str) -> float:
    """Parse 'X hrs Y mins' / 'Y min Z sec' / 'Z secs' into minutes (float)."""
    if not isinstance(s, str):
        return 0.0
    m = re.match(
        r"(?:(?P<h>\d+)\s*hrs?\s*)?(?:(?P<m1>\d+)\s*mins?\s*)?(?:(?P<s1>\d+)\s*secs?)?",
        s.strip(),
    )
    if not m:
        return 0.0
    return int(m["h"] or 0) * 60 + int(m["m1"] or 0) + int(m["s1"] or 0) / 60.0


def parse_hour(s: str) -> int:
    """Parse 'HH:MM:SS' into hour-of-day (0-23)."""
    try:
        return int(pd.to_datetime(s, format="%H:%M:%S").hour)
    except Exception:
        return 0


@st.cache_data
def load_data(path: str) -> pd.DataFrame:
    """Load the gaps CSV once and derive numeric columns for charting."""
    df = pd.read_csv(path)
    df["Gap_Minutes"] = df["Gap Duration"].map(parse_duration_minutes)
    df["Gap_Hours"] = df["Gap_Minutes"] / 60.0
    df["Gap_Hour"] = df["Gap_From"].map(parse_hour)
    # Pretty label for charts/legends; keeps original Gap_Type for filtering.
    df["Gap_Type_Label"] = df["Gap_Type"].map(GAP_LABELS).fillna(df["Gap_Type"])
    return df


def capacity_chart(filt: pd.DataFrame) -> go.Figure:
    """Stacked horizontal bar: total free hours per robot by Gap_Type."""
    if filt.empty:
        return go.Figure()
    summary = (
        filt.groupby(["robotName", "Gap_Type_Label"])["Gap_Hours"]
        .sum()
        .reset_index()
        .sort_values("Gap_Hours")
    )
    color_map = {label: GAP_COLORS[gap] for gap, label in GAP_LABELS.items()}
    fig = px.bar(
        summary,
        x="Gap_Hours",
        y="robotName",
        color="Gap_Type_Label",
        color_discrete_map=color_map,
        barmode="stack",
        orientation="h",
        labels={"Gap_Hours": "Total Free Hours", "robotName": "Robot"},
        title="Robot Capacity Breakdown",
        hover_data={"Gap_Hours": ":.1f"},
    )
    fig.update_layout(xaxis_title="Total Free Hours", yaxis_title="Robot")
    return fig


def heatmap_chart(filt: pd.DataFrame) -> go.Figure:
    """Density heatmap: gap frequency by hour (Gap_From) x robot."""
    if filt.empty:
        return go.Figure()
    counts = pd.crosstab(filt["robotName"], filt["Gap_Hour"])
    counts = counts.reindex(
        columns=range(24), fill_value=0
    )  # all 24 hours, gaps = 0
    long = (
        counts.rename_axis(index="robotName", columns="Gap_Hour")
        .reset_index()
        .melt(id_vars="robotName", var_name="Gap_Hour", value_name="Gaps")
    )
    fig = px.density_heatmap(
        long,
        x="Gap_Hour",
        y="robotName",
        z="Gaps",
        color_continuous_scale="YlOrRd",
        labels={"Gap_Hour": "Hour of Day (0-23)", "robotName": "Robot", "Gaps": "Number of Gaps"},
        title="Gap Frequency by Hour & Robot",
    )
    fig.update_layout(xaxis_title="Hour of Day (0-23)", yaxis_title="Robot")
    return fig


def duration_chart(filt: pd.DataFrame) -> go.Figure:
    """Histogram of gap durations with min/max threshold lines."""
    if filt.empty:
        return go.Figure()
    fig = px.histogram(
        filt,
        x="Gap_Minutes",
        nbins=30,
        color_discrete_sequence=["#3498db"],
        labels={"Gap_Minutes": "Gap Duration (minutes)"},
        title="Distribution of Free Slot Durations",
    )
    fig.update_traces(marker_line_width=1, marker_line_color="black")
    fig.add_vline(
        x=MIN_GAP_MINUTES, line_dash="dash", line_color="#e74c3c",
        annotation_text=f"Min {MIN_GAP_MINUTES} min",
    )
    fig.add_vline(
        x=MAX_GAP_HOURS * 60, line_dash="dash", line_color="#9b59b6",
        annotation_text=f"Max {MAX_GAP_HOURS} hrs",
    )
    return fig


def format_minutes(minutes: int) -> str:
    """Format the slider value for display, e.g. 120 -> '≥ 2h 00m'."""
    if minutes == 0:
        return "Any length"
    if minutes < 60:
        return f"≥ {minutes} min"
    return f"≥ {minutes // 60}h {minutes % 60:02d}m"


def render_filters(df: pd.DataFrame) -> tuple[list, list, list, float]:
    """Render the sidebar filter panel and return the selection.

    Returns (robots, gap_types, weekdays, min_minutes) where an empty list
    means "no restriction". UX notes:
      - Robot: none selected = all robots; "Select all" shortcut button.
      - Weekday: Mon–Fri / Weekend quick presets + calendar-ordered list.
      - Duration slider: only gaps >= chosen length are shown, so users can
        answer "what fits my job?" without re-running the pipeline.
        (st.select_slider returns a single value, not a tuple.)
    """
    with st.sidebar:
        st.header("Filters")
        st.caption("Empty = show all. Filters combine (AND).")

        # Robot ------------------------------------------------------------
        st.subheader("Robot")
        robot_options = sorted(df["robotName"].unique())
        if st.button("Select all robots", use_container_width=True):
            st.session_state["robot_sel"] = robot_options
        robots = st.multiselect(
            "Robots", robot_options,
            key="robot_sel",
            placeholder="All robots (none selected)",
            help="Leave empty to include every robot.",
        )
        st.caption(f"Selected: **{len(robots) or len(robot_options)}** of {len(robot_options)}")

        # Gap type ---------------------------------------------------------
        st.subheader("Gap type")
        gap_type_options = [GAP_LABELS[g] for g in GAP_LABELS if g in df["Gap_Type"].unique()]
        gap_labels = st.multiselect(
            "Gap types", gap_type_options, default=gap_type_options,
            help="Available = safe to schedule · Reserved = same-process queue · "
                 "Post-error = after a failure (outside the retry window).",
        )
        gap_types = [LABEL_TO_GAP[g] for g in gap_labels]

        # Weekday ----------------------------------------------------------
        st.subheader("Weekday")
        col1, col2 = st.columns(2)
        if col1.button("Weekdays", use_container_width=True):
            st.session_state["weekday_sel"] = [d for d in WEEKDAY_ORDER if d in df["WeekDay"].unique()][:5]
        if col2.button("Weekends", use_container_width=True):
            st.session_state["weekday_sel"] = [d for d in WEEKDAY_ORDER if d in df["WeekDay"].unique()][5:]
        weekday_options = [d for d in WEEKDAY_ORDER if d in df["WeekDay"].unique()]
        weekdays = st.multiselect(
            "Weekdays", weekday_options, key="weekday_sel",
            placeholder="All weekdays (none selected)",
        )

        # Min duration -----------------------------------------------------
        st.subheader("Minimum gap length")
        min_minutes = st.select_slider(
            "Only show gaps at least this long",
            options=MIN_DURATION_OPTIONS,
            value=0,
            format_func=format_minutes,
            help="E.g. choose at least 120 min to see only 2-hour+ slots that fit a long job.",
        )

        st.divider()
        if st.button("Clear all filters", use_container_width=True):
            for key in ["robot_sel", "weekday_sel"]:
                st.session_state[key] = []
            st.rerun()

    return robots, gap_types, weekdays, float(min_minutes)


def main() -> None:
    """Render the dashboard."""
    st.title("UiPath Robot Capacity & Gap Analysis")
    st.caption(
        "Idle-window analysis between consecutive UiPath jobs · "
        "source: `data/Free_Slots_Analysis.csv` · see README for methodology"
    )

    if not DATA_CSV.exists():
        st.error(
            f"Data file missing: `{DATA_CSV}` run `python free_slots_v2.py` first."
        )
        return

    df = load_data(str(DATA_CSV))

    robots, gap_types, weekdays, min_minutes = render_filters(df)

    filt = df
    if robots:
        filt = filt[filt["robotName"].isin(robots)]
    if gap_types:
        filt = filt[filt["Gap_Type"].isin(gap_types)]
    if weekdays:
        filt = filt[filt["WeekDay"].isin(weekdays)]
    if min_minutes:
        filt = filt[filt["Gap_Minutes"] >= min_minutes]

    total_all = len(df)
    st.caption(f"Showing **{len(filt):,}** of {total_all:,} gaps")

    # --- KPI cards ----------------------------------------------------------
    total = len(filt)
    available = int((filt["Gap_Type"] == "Available").sum())
    reserved = int((filt["Gap_Type"] == "Reserved_Same_Process").sum())
    post_error = int((filt["Gap_Type"] == "Post_Error_Window").sum())

    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Total gaps", total)
    k2.metric("Available (safe)", available, f"{total and available / total * 100:.1f}%")
    k3.metric("Reserved", reserved, f"{total and reserved / total * 100:.1f}%")
    k4.metric("Post-error", post_error)

    if total == 0:
        st.warning("No gaps match the current filters try clearing a filter.")
        return

    # --- Interactive Plotly charts (all three update with filters) ----------
    st.subheader("Capacity breakdown Available vs Reserved")
    st.plotly_chart(capacity_chart(filt), use_container_width=True)

    st.subheader("Gap frequency heatmap")
    st.plotly_chart(heatmap_chart(filt), use_container_width=True)

    st.subheader("Duration distribution")
    st.plotly_chart(duration_chart(filt), use_container_width=True)

    # --- Data table (Power-BI-style drill-down) -----------------------------
    st.subheader("Gap detail")
    st.dataframe(
        filt.drop(columns=["Gap_Minutes", "Gap_Hours", "Gap_Hour", "Gap_Type_Label"]),
        use_container_width=True,
    )
    st.download_button(
        "Download filtered CSV",
        filt.to_csv(index=False).encode(),
        "filtered_free_slots.csv",
        "text/csv",
    )


if __name__ == "__main__":
    main()
